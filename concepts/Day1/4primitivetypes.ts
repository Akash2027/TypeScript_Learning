// Number
const age: number = 22;
const cgpa: number = 9.24;
console.log("Age:", age);
console.log("CGPA:", cgpa);

// Boolean
const isPresent: boolean = true;
console.log("Attendance:", isPresent);

// Undefined
const missingValue: undefined = undefined;
console.log("Undefined Value:", missingValue);

// Null
const emptyValue: null = null;
console.log("Null Value:", emptyValue);
